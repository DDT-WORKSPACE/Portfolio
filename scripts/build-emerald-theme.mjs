// Generates app/theme-emerald.css: the "Emerald & gold" colour theme.
//
// Every colour-related declaration of the loaded stylesheets is copied, recoloured with
// scripts/emerald-palette.mjs and scoped under html[data-theme="emerald"]. All declarations
// of the involved properties are copied (not only the coloured ones), so the original cascade
// order and specificity relationships survive inside the theme. Keyframes that contain colours
// get an "-em" copy and the animations that use them are pointed at the copy.
//
//   node scripts/build-emerald-theme.mjs
import postcss from "postcss";
import { readFile, writeFile } from "node:fs/promises";
import { mapHex, mapRgb } from "./emerald-palette.mjs";

const files = ["globals.css", "experience.css", "refinements.css", "studio.css", "brand.css"];
const P = 'html[data-theme="emerald"]';

const colourProp =
  /^(color|background(-color|-image)?|background|border(?!.*radius)(-[a-z-]+)?|outline(-color)?|box-shadow|text-shadow|fill|stroke|stop-color|caret-color|accent-color|text-decoration(-color)?|column-rule(-color)?|filter|-webkit-text-fill-color|-webkit-text-stroke(-color)?|scrollbar-color)$/i;
const skipProp = /^(border-collapse|border-spacing|border-image.*)$/i;

const HEX = /#(?:[0-9a-f]{8}|[0-9a-f]{6}|[0-9a-f]{3,4})\b/gi;
const RGB = /rgba?\(\s*(\d+(?:\.\d+)?)[\s,]+(\d+(?:\.\d+)?)[\s,]+(\d+(?:\.\d+)?)\s*(?:[,/]\s*([\d.]+%?))?\s*\)/gi;

function recolour(value) {
  // Leave url(...) payloads (data URIs, masks) untouched.
  return value
    .split(/(url\([^)]*\))/g)
    .map((part) =>
      part.startsWith("url(")
        ? part
        : part
            .replace(HEX, (m) => mapHex(m))
            .replace(RGB, (m, r, g, b, a) => {
              const [R, G, B] = mapRgb(+r, +g, +b);
              return a !== undefined ? `rgba(${R}, ${G}, ${B}, ${a})` : `rgb(${R}, ${G}, ${B})`;
            }),
    )
    .join("");
}
const hasColour = (v) => recolour(v) !== v;

function scope(sel) {
  sel = sel.trim();
  if (sel.startsWith(":root")) return P + sel.slice(5);
  if (/^html\b/.test(sel)) return P + sel.slice(4);
  return `${P} ${sel}`;
}

const out = postcss.root();
const keyframeNames = new Set();
let kept = 0;

for (const file of files) {
  const css = await readFile(`app/${file}`, "utf8");
  const root = postcss.parse(css, { from: `app/${file}` });

  // Keyframes with colours -> recoloured copies.
  root.walkAtRules(/keyframes$/i, (kf) => {
    let coloured = false;
    kf.walkDecls((d) => {
      if (hasColour(d.value)) coloured = true;
    });
    if (!coloured) return;
    keyframeNames.add(kf.params.trim());
    const copy = kf.clone({ params: `${kf.params.trim()}-em` });
    copy.walkDecls((d) => {
      d.value = recolour(d.value);
    });
    out.append(copy);
  });

  root.walkRules((rule) => {
    const parent = rule.parent;
    if (parent?.type === "atrule" && /keyframes$/i.test(parent.name)) return;
    // Skip rules inside @theme / @layer base of Tailwind internals except plain @media/@supports chains.
    for (let p = parent; p && p.type !== "root"; p = p.parent) {
      if (p.type === "atrule" && !/^(media|supports|container)$/i.test(p.name)) return;
    }
    const decls = [];
    rule.each((node) => {
      if (node.type !== "decl") return;
      const prop = node.prop;
      if (prop.startsWith("--")) {
        if (hasColour(node.value)) decls.push(node.clone({ value: recolour(node.value) }));
        return;
      }
      if (/^(animation|animation-name)$/i.test(prop)) {
        const names = [...keyframeNames].filter((n) => new RegExp(`(^|[\\s,])${n}([\\s,]|$)`).test(node.value));
        if (names.length) {
          let v = node.value;
          for (const n of names) v = v.replace(new RegExp(`(^|[\\s,])${n}(?=[\\s,]|$)`, "g"), `$1${n}-em`);
          decls.push(node.clone({ value: v }));
        }
        return;
      }
      if (colourProp.test(prop) && !skipProp.test(prop)) decls.push(node.clone({ value: recolour(node.value) }));
    });
    if (!decls.length) return;
    const r = postcss.rule({ selectors: rule.selectors.map(scope) });
    decls.forEach((d) => r.append(d));
    // Rebuild the at-rule chain.
    let node = r;
    for (let p = parent; p && p.type !== "root"; p = p.parent) {
      const wrap = postcss.atRule({ name: p.name, params: p.params });
      wrap.append(node);
      node = wrap;
    }
    out.append(node);
    kept++;
  });
}

const header = `/* GENERATED by scripts/build-emerald-theme.mjs. Do not edit; edit app/theme-emerald-overrides.css. */\n`;
await writeFile("app/theme-emerald.css", header + out.toString() + "\n");
console.log(`theme-emerald.css: ${kept} rules, ${keyframeNames.size} recoloured keyframes`);
